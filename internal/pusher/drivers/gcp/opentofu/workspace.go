package opentofu

import (
	"context"
	"encoding/json"
	"fmt"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strings"
)

// Workspace is one intent's isolated tofu directory.
type Workspace struct {
	backend   *Backend
	dir       string
	partition string
	intent    string
	asset     string
	lock      *os.File
	closed    bool
}

// Dir returns the workspace directory.
func (w *Workspace) Dir() string { return w.dir }

// Partition returns the partition name.
func (w *Workspace) Partition() string { return w.partition }

// Intent returns the intent name.
func (w *Workspace) Intent() string { return w.intent }

// StatePrefix returns the GCS object prefix used by this workspace.
func (w *Workspace) StatePrefix() string {
	if w.asset == "" {
		return w.backend.StatePrefix(w.partition, w.intent)
	}
	return w.backend.StatePrefix(w.partition, w.intent, w.asset)
}

// WriteBlueprint writes blueprint files relative to the workspace root. Paths
// must stay inside the workspace; absolute paths and ".." are rejected.
func (w *Workspace) WriteBlueprint(files map[string]string) error {
	if len(files) == 0 {
		return fmt.Errorf("opentofu: blueprint has no files")
	}
	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		clean := path.Clean(strings.TrimSpace(name))
		if clean == "" || clean == "." || path.IsAbs(clean) || strings.HasPrefix(clean, "../") || clean == ".." {
			return fmt.Errorf("opentofu: invalid blueprint path %q", name)
		}
		dest := filepath.Join(w.dir, filepath.FromSlash(clean))
		if err := os.MkdirAll(filepath.Dir(dest), 0o700); err != nil {
			return fmt.Errorf("opentofu: create %q: %w", filepath.Dir(dest), err)
		}
		if err := os.WriteFile(dest, []byte(files[name]), 0o600); err != nil {
			return fmt.Errorf("opentofu: write %q: %w", dest, err)
		}
	}
	return nil
}

// WriteVariables writes terraform.tfvars.json.
func (w *Workspace) WriteVariables(vars map[string]any) error {
	payload, err := json.MarshalIndent(vars, "", "  ")
	if err != nil {
		return fmt.Errorf("opentofu: encode variables: %w", err)
	}
	payload = append(payload, '\n')
	dest := filepath.Join(w.dir, variablesFile)
	if err := os.WriteFile(dest, payload, 0o600); err != nil {
		return fmt.Errorf("opentofu: write variables: %w", err)
	}
	return nil
}

// writeBackendConfig generates the backend and state-encryption blocks.
func (w *Workspace) writeBackendConfig() error {
	var b strings.Builder
	b.WriteString("# Generated by guardian. Do not edit.\n")
	b.WriteString("terraform {\n")
	b.WriteString("  required_version = \">= 1.9\"\n")
	b.WriteString("  backend \"gcs\" {}\n")
	if key := strings.TrimSpace(w.backend.cfg.StateKMSKey); key != "" {
		b.WriteString("\n  encryption {\n")
		fmt.Fprintf(&b, "    key_provider \"gcp_kms\" \"state\" {\n      kms_encryption_key = %q\n      key_length         = 32\n    }\n", key)
		b.WriteString("    method \"aes_gcm\" \"state\" {\n      keys = key_provider.gcp_kms.state\n    }\n")
		b.WriteString("    state {\n      method = method.aes_gcm.state\n    }\n")
		b.WriteString("    plan {\n      method = method.aes_gcm.state\n    }\n")
		b.WriteString("  }\n")
	}
	b.WriteString("}\n")

	dest := filepath.Join(w.dir, backendFile)
	if err := os.WriteFile(dest, []byte(b.String()), 0o600); err != nil {
		return fmt.Errorf("opentofu: write backend config: %w", err)
	}
	return nil
}

// Init prepares providers and the GCS backend.
func (w *Workspace) Init(ctx context.Context) error {
	if err := w.writeBackendConfig(); err != nil {
		return err
	}
	args := []string{
		"init",
		"-input=false",
		"-no-color",
		"-backend-config=bucket=" + w.backend.cfg.StateBucket,
		"-backend-config=prefix=" + w.StatePrefix(),
	}
	stdout, stderr, err := w.backend.run(ctx, w.dir, args...)
	if err != nil {
		return commandError("tofu init", stdout, stderr, err)
	}
	return nil
}

// Plan runs a plan and reports whether it contains changes.
func (w *Workspace) Plan(ctx context.Context) (PlanResult, error) {
	stdout, stderr, err := w.backend.run(ctx,
		w.dir,
		"plan", "-input=false", "-no-color", "-detailed-exitcode", "-json",
	)
	result := ParsePlan(stdout)
	switch ExitCode(err) {
	case 0:
		result.Drift = false
		return result, nil
	case 2:
		result.Drift = true
		return result, nil
	default:
		err = commandError("tofu plan", stdout, stderr, err)
		if len(result.Diagnostics) > 0 {
			err = fmt.Errorf("%w\n%s", err, strings.Join(result.Diagnostics, "\n"))
		}
		return result, err
	}
}

// Apply applies the workspace with auto-approval.
func (w *Workspace) Apply(ctx context.Context) error {
	stdout, stderr, err := w.backend.run(ctx,
		w.dir,
		"apply", "-input=false", "-no-color", "-auto-approve",
	)
	if err != nil {
		return commandError("tofu apply", stdout, stderr, err)
	}
	return nil
}

// Destroy destroys the workspace resources.
func (w *Workspace) Destroy(ctx context.Context) error {
	stdout, stderr, err := w.backend.run(ctx,
		w.dir,
		"destroy", "-input=false", "-no-color", "-auto-approve",
	)
	if err != nil {
		return commandError("tofu destroy", stdout, stderr, err)
	}
	return nil
}

// Output returns the workspace outputs as strings. Structured values are
// returned as compact JSON.
func (w *Workspace) Output(ctx context.Context) (map[string]string, error) {
	stdout, stderr, err := w.backend.run(ctx, w.dir, "output", "-json", "-no-color")
	if err != nil {
		return nil, commandError("tofu output", stdout, stderr, err)
	}
	var raw map[string]struct {
		Value     json.RawMessage `json:"value"`
		Sensitive bool            `json:"sensitive"`
	}
	if err := json.Unmarshal(stdout, &raw); err != nil {
		return nil, fmt.Errorf("opentofu: decode outputs: %w", err)
	}
	out := make(map[string]string, len(raw))
	for name, entry := range raw {
		out[name] = decodeScalar(entry.Value)
	}
	return out, nil
}

// StateList returns the addresses of resources in the workspace state.
func (w *Workspace) StateList(ctx context.Context) ([]string, error) {
	stdout, stderr, err := w.backend.run(ctx, w.dir, "state", "list")
	if err != nil {
		return nil, commandError("tofu state list", stdout, stderr, err)
	}
	lines := strings.Split(strings.TrimSpace(string(stdout)), "\n")
	out := make([]string, 0, len(lines))
	for _, line := range lines {
		if line = strings.TrimSpace(line); line != "" {
			out = append(out, line)
		}
	}
	return out, nil
}

// Close releases the workspace lock and, unless KeepWorkspace is set, removes
// the directory.
func (w *Workspace) Close() error {
	if w == nil || w.closed {
		return nil
	}
	w.closed = true
	var firstErr error
	if w.lock != nil {
		if err := releaseLock(w.lock); err != nil {
			firstErr = err
		}
		w.lock = nil
	}
	if !w.backend.cfg.KeepWorkspace {
		if err := os.RemoveAll(w.dir); err != nil && firstErr == nil {
			firstErr = fmt.Errorf("opentofu: remove workspace: %w", err)
		}
	}
	return firstErr
}

func commandError(prefix string, stdout, stderr []byte, err error) error {
	detail := strings.TrimSpace(string(stderr))
	if detail == "" {
		detail = strings.TrimSpace(string(stdout))
	}
	if detail == "" {
		return fmt.Errorf("%s: %w", prefix, err)
	}
	return fmt.Errorf("%s: %w: %s", prefix, err, detail)
}

func decodeScalar(raw json.RawMessage) string {
	if len(raw) == 0 {
		return ""
	}
	var str string
	if err := json.Unmarshal(raw, &str); err == nil {
		return str
	}
	var num json.Number
	if err := json.Unmarshal(raw, &num); err == nil {
		return num.String()
	}
	var boolean bool
	if err := json.Unmarshal(raw, &boolean); err == nil {
		return fmt.Sprintf("%t", boolean)
	}
	var compact any
	if err := json.Unmarshal(raw, &compact); err == nil {
		if encoded, err := json.Marshal(compact); err == nil {
			return string(encoded)
		}
	}
	return strings.TrimSpace(string(raw))
}
